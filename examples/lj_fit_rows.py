"""Fit one pair's Lennard-Jones parameters to labeled frames.

``data/lj_frames.npz`` holds 300 frames of 216 atoms of two types with their energies,
forces and virials, generated by a Lennard-Jones potential with sigma rows (0.34, 0.32,
0.30) nm and epsilon rows (1.0, 0.6, 0.8) kJ/mol for the pairs (0,0), (0,1), (1,1),
shifted to zero at the cutoff of 1.0 nm: three NVT runs at 180 K in cubic cells of 2.2,
2.8 and 3.8 nm, 100 frames each, in that order. The rows of the pairs (0,0) and (1,1)
are known and held fixed; the fit starts the row of the cross pair (0,1) with sigma 10% high
and epsilon 30% low, trains it alone on the first 80 frames of each run and validates on
the last 20.
"""

from pathlib import Path

import numpy as np
import torch
from matplotlib.figure import Figure

from nabladyn import potential, training

DATA = Path(__file__).resolve().parent / "data" / "lj_frames.npz"


def main():
    dtype = torch.float64
    device = "cuda"
    runs = 3
    train_per_run = 80  # frames; the rest of each run validates
    updates = 1000
    batch_size = 48  # frames
    learning_rate = 1e-2
    settle_after = 800  # updates; then the rate falls to a tenth, so the fit settles
    echo_every = 100  # updates
    figure_file = "lj_fit_rows.png"  # the loss per update

    data = np.load(DATA)
    sigma, epsilon = data["sigma"], data["epsilon"]  # the rows that generated the frames
    frames = training.Dataset(
        data["positions"],
        data["cells"],
        energy=data["energy"],
        forces=data["forces"],
        virial=data["virial"],
    )
    # Split each run in time: consecutive frames are correlated, so validation takes each
    # run's last frames rather than frames between training ones.
    split = np.split(np.arange(len(frames)), runs)
    train = frames[np.concatenate([run[:train_per_run] for run in split])]
    validation = frames[np.concatenate([run[train_per_run:] for run in split])]

    model = potential.lennard_jones(
        atom_types=torch.as_tensor(data["atom_types"], device=device),
        sigma=torch.tensor(sigma * [1.0, 1.10, 1.0], dtype=dtype, device=device),
        epsilon=torch.tensor(epsilon * [1.0, 0.7, 1.0], dtype=dtype, device=device),
        cutoff=float(data["cutoff"]),
        trainable={"sigma": [1], "epsilon": [1]},  # the row of (0,1) alone
    )
    optimizer = torch.optim.Adam(model.parameters(), lr=learning_rate)
    scheduler = torch.optim.lr_scheduler.StepLR(optimizer, step_size=settle_after, gamma=0.1)
    report = training.fit(
        model,
        train,
        optimizer,
        updates=updates,
        batch_size=batch_size,
        energy=1.0,
        forces=1.0,
        virial=1.0,
        validation=validation,
        scheduler=scheduler,
        echo_every=echo_every,
    )

    print("Validation RMS error, before -> after:")
    for name, unit in (("energy", "kJ/mol"), ("forces", "kJ/mol/nm"), ("virial", "kJ/mol")):
        before, after = report.validation[name]
        print(f"  {name:7s} {before:.4g} -> {after:.4g} {unit}")
    print("Pair rows (0,0), (0,1), (1,1):")
    for name, generating in (("sigma", sigma), ("epsilon", epsilon)):
        fitted = getattr(model, name).detach().cpu().numpy()
        print(f"  {name:7s} generated {np.round(generating, 4)}, fitted {np.round(fitted, 4)}")

    figure = Figure(figsize=(6.0, 4.0), layout="constrained")
    axes = figure.subplots()
    axes.semilogy(np.arange(1, updates + 1), report.loss, linewidth=0.8)
    axes.axvline(settle_after, color="gray", linestyle=":", label="learning rate x 0.1")
    axes.legend()
    axes.set_xlabel("update")
    axes.set_ylabel("batch loss")
    figure.savefig(figure_file, dpi=150)
    print(f"Wrote {figure_file}")
    return model, report


if __name__ == "__main__":
    main()
